"""Turn results/before.txt and results/after.txt into results/summary.md.

Run from this folder after benchmark.sql:

    python summarise.py

For each query it reports the execution time and the number of 8 kB pages
read, before and after the indexes, and which of the new indexes the
optimiser chose to use.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"

HEADING = re.compile(r"^-- (Q\d+[a-z]?): (.+)$")
EXEC_TIME = re.compile(r"Execution Time: ([\d.]+) ms")
BUFFERS = re.compile(r"Buffers: shared(?: hit=(\d+))?(?: read=(\d+))?")
INDEX_USED = re.compile(r"(?:Index Only Scan|Index Scan|Bitmap Index Scan) (?:using|on) (\w+)")


def new_index_names():
    """Names of the indexes created by 03_indexes.sql."""
    sql = (HERE / "03_indexes.sql").read_text(encoding="utf-8")
    return set(re.findall(r"CREATE INDEX (\w+)", sql))


def read_text(path):
    # psql on Windows may write the file in UTF-16 when run from PowerShell
    data = path.read_bytes()
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16")
    return data.decode("utf-8", errors="replace")


def parse(path):
    """Return {query id: {title, ms, pages, indexes}} for one output file."""
    queries, current = {}, None
    for line in read_text(path).splitlines():
        heading = HEADING.match(line)
        if heading:
            current = {"title": heading.group(2), "ms": None, "pages": None, "indexes": []}
            queries[heading.group(1)] = current
            continue
        if current is None:
            continue
        buffers = BUFFERS.search(line)
        if buffers and current["pages"] is None:
            # the first Buffers line belongs to the top node: the whole query
            current["pages"] = int(buffers.group(1) or 0) + int(buffers.group(2) or 0)
        for name in INDEX_USED.findall(line):
            if name not in current["indexes"]:
                current["indexes"].append(name)
        timing = EXEC_TIME.search(line)
        if timing:
            current["ms"] = float(timing.group(1))
    return queries


def fmt_ms(ms):
    return f"{ms:,.0f}" if ms >= 100 else f"{ms:.2f}" if ms < 10 else f"{ms:.1f}"


def fmt_change(before, after):
    if after <= 0:
        return "-"
    ratio = before / after
    if ratio >= 1.15:
        return f"{ratio:,.0f}x faster" if ratio >= 10 else f"{ratio:.1f}x faster"
    if ratio <= 0.87:
        return f"{1 / ratio:.1f}x slower"
    return "about the same"


def main():
    before = parse(RESULTS / "before.txt")
    after = parse(RESULTS / "after.txt")
    created = new_index_names()

    lines = [
        "# Benchmark summary",
        "",
        "Generated by `summarise.py` from `before.txt` and `after.txt`.",
        "A page is 8 kB. Times are from the second of two runs.",
        "",
        "| Query | Question | Before (ms) | After (ms) | Change | Pages before | Pages after | New indexes used |",
        "|---|---|---:|---:|---|---:|---:|---|",
    ]
    for qid, b in before.items():
        a = after.get(qid)
        if a is None or b["ms"] is None or a["ms"] is None:
            continue
        used = [name for name in a["indexes"] if name in created]
        lines.append(
            f"| {qid} | {b['title']} | {fmt_ms(b['ms'])} | {fmt_ms(a['ms'])} | "
            f"{fmt_change(b['ms'], a['ms'])} | {b['pages']:,} | {a['pages']:,} | "
            f"{', '.join(f'`{n}`' for n in used) or 'none'} |"
        )

    text = "\n".join(lines) + "\n"
    (RESULTS / "summary.md").write_text(text, encoding="utf-8")
    print(text)
    print(f"Written to {RESULTS / 'summary.md'}")


if __name__ == "__main__":
    main()
